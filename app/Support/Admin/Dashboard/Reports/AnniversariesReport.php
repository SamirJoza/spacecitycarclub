/**
 * Render the Anniversaries dashboard widget
 * - Shows a compact table preview (first 10 rows)
 * - Provides a "Print list" button that opens a standalone print page
 */
function sccc_anniversaries_widget_render(): void
{
  if (!current_user_can(\App\Support\Admin\UserRoles\OperationalRoles::CAP_USE_DASHBOARD_WIDGETS)) {
    echo '<p>You do not have permission to view this report.</p>';
    return;
  }

  $monthNum  = (int) wp_date('n');
  $monthName = wp_date('F');

  $members = sccc_get_members_with_anniversary_in_month($monthNum);

  $printUrl = add_query_arg(
    [
      'action'    => 'sccc_print_anniversaries',
      'month'     => $monthNum,
      'autoprint' => 1,
    ],
    admin_url('admin-post.php')
  );

  $printUrl = wp_nonce_url($printUrl, 'sccc_print_anniversaries');

  echo '<p style="margin:0 0 .75rem;">';
  echo 'Showing members with anniversaries in <strong>' . esc_html($monthName) . '</strong>.';
  echo '</p>';

  echo '<p style="margin:0 0 1rem;">';
  echo '<a class="button button-primary" href="' . esc_url($printUrl) . '">Print list</a>';
  echo '</p>';

  if (empty($members)) {
    echo '<p style="margin:0;">No anniversaries found for this month.</p>';
    return;
  }

  $preview = array_slice($members, 0, 10);

  echo '<div style="max-height: 260px; overflow:auto; border:1px solid #dcdcde; border-radius:6px;">';
  echo '<table class="widefat striped" style="margin:0;">';
  echo '<thead><tr>';
  echo '<th style="width:130px;">Anniversary</th>';
  echo '<th style="width:80px;">Years</th>';
  echo '<th>Name</th>';
  echo '<th>Email</th>';
  echo '</tr></thead><tbody>';

  foreach ($preview as $row) {
    echo '<tr>';
    echo '<td>' . esc_html($row['anniversary_label']) . '</td>';
    echo '<td>' . esc_html((string) $row['years']) . '</td>';
    echo '<td>' . esc_html($row['name']) . '</td>';
    echo '<td>' . esc_html($row['email']) . '</td>';
    echo '</tr>';
  }

  echo '</tbody></table></div>';

  $total = count($members);
  if ($total > count($preview)) {
    echo '<p style="margin:.75rem 0 0; color:#646970;">';
    echo esc_html(sprintf('Showing %d of %d. Use “Print list” for the full sheet.', count($preview), $total));
    echo '</p>';
  }
}

