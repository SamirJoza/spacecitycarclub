/**
 * ---------------------------------------------------------------------------
 * Data helper: members with anniversaries in a given month
 * ---------------------------------------------------------------------------
 *
 * Anniversary definition:
 * - Month of `membership_issued_at` matches the report month
 *
 * Years:
 * - reportYear - issuedYear
 *
 * EXCLUSION (requested):
 * - We skip 0-year anniversaries (issuedYear === reportYear)
 *
 * ADDITIONAL EXCLUSION (your new rule):
 * - Only include members who are Active or in Grace (0–29 days lapsed)
 * - Exclude Past Due, Abandoned, and Paused
 */
function sccc_get_members_with_anniversary_in_month(int $monthNum): array
{
  $monthNum   = max(1, min(12, $monthNum));
  $reportYear = (int) wp_date('Y');

  $query = new WP_User_Query([
    'role'       => SCCC_REPORTS_MEMBER_ROLE,
    'number'     => 9999,
    'orderby'    => 'display_name',
    'order'      => 'ASC',
    'meta_query' => [
      [
        'key'     => SCCC_MEMBERSHIP_ISSUED_META_KEY,
        'compare' => 'EXISTS',
      ],
      [
        'key'     => SCCC_MEMBERSHIP_ISSUED_META_KEY,
        'value'   => '',
        'compare' => '!=',
      ],
    ],
  ]);

  $users = $query->get_results();
  if (empty($users)) {
    return [];
  }

  $rows = [];

  foreach ($users as $user) {
    /**
     * STATUS GATE (Active + Grace only)
     * -----------------------------------------------------------------------
     * Keeps the report focused on members who are realistically still part of
     * the club’s active community right now.
     */
    if (!sccc_reports_anniv_is_active_or_grace((int) $user->ID)) {
      continue;
    }

    $raw = (string) get_user_meta($user->ID, SCCC_MEMBERSHIP_ISSUED_META_KEY, true);
    if ($raw === '') {
      continue;
    }

    $issued = sccc_reports_parse_issued_date($raw);
    if (!$issued) {
      continue;
    }

    $issuedYear  = (int) $issued->format('Y');
    $issuedMonth = (int) $issued->format('n');
    $issuedDay   = (int) $issued->format('j');

    if ($issuedMonth !== $monthNum) {
      continue;
    }

    $years = ($issuedYear > 0) ? ($reportYear - $issuedYear) : '';

    // Skip 0-year anniversaries (members who joined this year)
    if ($years === '' || $years < 1) {
      continue;
    }

    $annThisYear = DateTime::createFromFormat('Y-n-j', $reportYear . '-' . $issuedMonth . '-' . $issuedDay);
    if (!$annThisYear) {
      continue;
    }

    $weekday = $annThisYear->format('D');
    $ordinal = sccc_ordinal((int) $annThisYear->format('j'));
    $label   = $weekday . ' ' . $ordinal;

    $rows[] = [
      'id'                => (int) $user->ID,
      'name'              => (string) $user->display_name,
      'email'             => (string) $user->user_email,
      'issued_raw'        => $raw,
      'day'               => $issuedDay,
      'anniversary_label' => $label,
      'years'             => $years,
    ];
  }

  usort($rows, function ($a, $b) {
    if ($a['day'] === $b['day']) {
      return strcasecmp($a['name'], $b['name']);
    }
    return $a['day'] <=> $b['day'];
  });

  return $rows;
}
