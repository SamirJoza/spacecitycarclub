/**
 * ---------------------------------------------------------------------------
 * Helper: ordinal day suffix
 * ---------------------------------------------------------------------------
 *
 * AnniversariesReport.php may also define sccc_ordinal().
 * Guard to avoid fatal redeclare if both files load.
 */
if (!function_exists('sccc_ordinal')) {
  function sccc_ordinal(int $n): string
  {
    $n = abs($n);
    $mod100 = $n % 100;

    if ($mod100 >= 11 && $mod100 <= 13) {
      return $n . 'th';
    }

    switch ($n % 10) {
      case 1: return $n . 'st';
      case 2: return $n . 'nd';
      case 3: return $n . 'rd';
      default: return $n . 'th';
    }
  }
}

/**
 * ---------------------------------------------------------------------------
 * MEMBERSHIP STATUS FILTER (Active + Grace only)
 * ---------------------------------------------------------------------------
 *
 * Birthdays are a “community engagement” list.
 * We exclude members who are seriously lapsed or paused to keep the list relevant.
 *
 * Definitions used here:
 * - Active: PMPro status='active' AND (enddate is empty OR enddate in future)
 * - Grace: membership ended, but within 0–29 days
 * - Past Due: 30–59 days (excluded)
 * - Abandoned: 60+ days (excluded)
 * - Paused: manual override (excluded)
 *
 * Notes:
 * - We compute directly from PMPro’s memberships_users table so this report is
 *   accurate on its own (does not depend on visiting the Users screen).
 * - Functions are uniquely prefixed for this file to avoid collisions.
 */
if (!function_exists('sccc_reports_bday_is_active_or_grace')) {
  function sccc_reports_bday_is_active_or_grace(int $user_id): bool
  {
    // Paused members are excluded from engagement lists.
    if ((int) get_user_meta($user_id, 'sccc_membership_paused', true) === 1) {
      return false;
    }

    // If PMPro table is missing, we can’t reliably decide. Safer to exclude.
    if (!sccc_reports_bday_pmpro_table_exists()) {
      return false;
    }

    $row = sccc_reports_bday_get_latest_pmpro_membership_row($user_id);
    if (!$row || !is_array($row)) {
      return false;
    }

    $now = current_time('timestamp');
    $status = isset($row['status']) ? (string) $row['status'] : '';
    $end_ts = sccc_reports_bday_parse_enddate_to_ts($row['enddate'] ?? null);

    // Active if PMPro says active AND enddate is empty OR in the future.
    $has_end = ($end_ts !== null);
    $active_by_enddate = (!$has_end) || ($end_ts > $now);

    if ($status === 'active' && $active_by_enddate) {
      return true;
    }

    // Grace if membership ended within the last 0–29 days.
    if ($has_end && $end_ts <= $now) {
      $days = (int) floor(max(0, $now - $end_ts) / DAY_IN_SECONDS);
      return ($days >= 0 && $days < 30);
    }

    return false;
  }
}

if (!function_exists('sccc_reports_bday_pmpro_table_exists')) {
  function sccc_reports_bday_pmpro_table_exists(): bool
  {
    global $wpdb;

    $table = sccc_reports_bday_pmpro_memberships_users_table();
    if (!$table) {
      return false;
    }

    $like = $wpdb->esc_like($table);
    $found = $wpdb->get_var($wpdb->prepare("SHOW TABLES LIKE %s", $like)); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared

    return !empty($found);
  }
}

if (!function_exists('sccc_reports_bday_pmpro_memberships_users_table')) {
  function sccc_reports_bday_pmpro_memberships_users_table(): string
  {
    global $wpdb;

    // If PMPro registered a property, prefer it.
    if (isset($wpdb->pmpro_memberships_users) && !empty($wpdb->pmpro_memberships_users)) {
      return (string) $wpdb->pmpro_memberships_users;
    }

    return (string) ($wpdb->prefix . 'pmpro_memberships_users');
  }
}

if (!function_exists('sccc_reports_bday_get_latest_pmpro_membership_row')) {
  function sccc_reports_bday_get_latest_pmpro_membership_row(int $user_id): ?array
  {
    global $wpdb;

    $table = sccc_reports_bday_pmpro_memberships_users_table();
    if (!$table) {
      return null;
    }

    // “Latest” row by modified timestamp (then id) best reflects current state.
    $sql = "
      SELECT id, status, startdate, enddate, modified, membership_id
      FROM {$table}
      WHERE user_id = %d
      ORDER BY modified DESC, id DESC
      LIMIT 1
    ";

    $row = $wpdb->get_row($wpdb->prepare($sql, $user_id), ARRAY_A); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared

    return is_array($row) ? $row : null;
  }
}

if (!function_exists('sccc_reports_bday_parse_enddate_to_ts')) {
  function sccc_reports_bday_parse_enddate_to_ts($enddate): ?int
  {
    if ($enddate === null) {
      return null;
    }

    $enddate = is_string($enddate) ? trim($enddate) : '';
    if ($enddate === '' || $enddate === '0000-00-00 00:00:00') {
      return null;
    }

    $ts = strtotime($enddate);
    return $ts ? (int) $ts : null;
  }
}

