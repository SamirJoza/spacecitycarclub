/**
 * ---------------------------------------------------------------------------
 * Data helper: members with birthdays in a given month
 * ---------------------------------------------------------------------------
 *
 * We intentionally do NOT attempt month matching in SQL because:
 * - WP escapes "_" and "%" for LIKE comparisons in meta queries
 *
 * Instead:
 * - Query role sccc_member with a non-empty birth_date
 * - Filter month in PHP
 * - Filter status in PHP: Active + Grace only (exclude Past Due/Abandoned/Paused)
 *
 * Birthday label format:
 * - "Mon 16th" (weekday abbreviation + ordinal day)
 *
 * Age:
 * - The age the member is (or turns) in the report year on their birthday
 */
function sccc_get_members_with_birthdays_in_month(int $monthNum): array
{
  $monthNum = max(1, min(12, $monthNum));
  $reportYear = (int) wp_date('Y');

  $query = new WP_User_Query([
    'role'       => SCCC_REPORTS_MEMBER_ROLE,
    'number'     => 9999, // internal report; bump if you ever exceed this
    'orderby'    => 'display_name',
    'order'      => 'ASC',
    'meta_query' => [
      [
        'key'     => SCCC_BIRTH_DATE_META_KEY,
        'compare' => 'EXISTS',
      ],
      [
        'key'     => SCCC_BIRTH_DATE_META_KEY,
        'value'   => '',
        'compare' => '!=',
      ],
    ],
  ]);

  $users = $query->get_results();
  if (empty($users)) {
    return [];
  }

  $rows = [];

  foreach ($users as $user) {
    /**
     * STATUS GATE (Active + Grace only)
     * -----------------------------------------------------------------------
     * Keeps the report focused on members who are realistically still part of
     * the club’s active community right now.
     */
    if (!sccc_reports_bday_is_active_or_grace((int) $user->ID)) {
      continue;
    }

    $raw = (string) get_user_meta($user->ID, SCCC_BIRTH_DATE_META_KEY, true);
    if ($raw === '') {
      continue;
    }

    // Support the two most common storage formats:
    // - Ymd (ACF DB storage): 19530116
    // - Y-m-d: 1953-01-16
    if (preg_match('/^\d{8}$/', $raw)) {
      $dob = DateTime::createFromFormat('Ymd', $raw);
    } elseif (preg_match('/^\d{4}-\d{2}-\d{2}$/', $raw)) {
      $dob = DateTime::createFromFormat('Y-m-d', $raw);
    } else {
      continue; // unknown format
    }

    if (!$dob) {
      continue;
    }

    $dobYear  = (int) $dob->format('Y');
    $dobMonth = (int) $dob->format('n');
    $dobDay   = (int) $dob->format('j');

    if ($dobMonth !== $monthNum) {
      continue;
    }

    // For display and age, use the birthday in the current report year.
    $bdayThisYear = DateTime::createFromFormat('Y-n-j', $reportYear . '-' . $dobMonth . '-' . $dobDay);
    if (!$bdayThisYear) {
      continue;
    }

    $weekday = $bdayThisYear->format('D');                 // Mon/Tue/...
    $ordinal = sccc_ordinal((int) $bdayThisYear->format('j')); // 16th
    $label   = $weekday . ' ' . $ordinal;                  // "Mon 16th"

    $age = ($dobYear > 0) ? ($reportYear - $dobYear) : '';

    $rows[] = [
      'id'             => (int) $user->ID,
      'name'           => (string) $user->display_name,
      'email'          => (string) $user->user_email,
      'birth_date_raw' => $raw,
      'day'            => $dobDay, // used for sorting within the month
      'birthday_label' => $label,
      'age'            => $age,
    ];
  }

  // Sort by day-of-month, then by name
  usort($rows, function ($a, $b) {
    if ($a['day'] === $b['day']) {
      return strcasecmp($a['name'], $b['name']);
    }
    return $a['day'] <=> $b['day'];
  });

  return $rows;
}
