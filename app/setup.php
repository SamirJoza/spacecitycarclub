/* =============================================================================
 * BLOCK EDITOR ASSET INJECTION
 * =============================================================================
 *
 * These hooks connect Sage/Vite-built editor assets to Gutenberg.
 *
 * Why this lives here:
 * - These are theme-wide editor concerns, not page-specific or module-specific.
 * - Keeping them near the top makes it obvious how editor styles/scripts enter
 *   WordPress.
 *
 * Sage/Vite context:
 * - The theme uses Vite-generated `editor.css`, `editor.js`, and the generated
 *   dependency manifest to support the block editor experience.
 * - The `Vite` facade is used to resolve built assets from PHP.
 * =============================================================================
 */

/**
 * Inject compiled editor styles into the block editor settings payload.
 *
 * Why this approach:
 * - This makes the compiled editor stylesheet available inside Gutenberg without
 *   manually hardcoding the built file path.
 * - It keeps the editor using the same build pipeline as the frontend theme.
 *
 * @param array $settings Existing block editor settings array.
 * @return array
 */
add_filter('block_editor_settings_all', function ($settings) {
    $style = Vite::asset('resources/css/editor.css');

    $settings['styles'][] = [
        'css' => "@import url('{$style}')",
    ];

    return $settings;
});

/**
 * Inject compiled editor scripts and any generated dependencies into Gutenberg.
 *
 * Why this exists:
 * - Some block editor scripts may rely on dependency handles generated by the
 *   Vite/Laravel build process.
 * - This hook ensures those dependencies are enqueued before the editor entry
 *   script is printed.
 *
 * Why `admin_head` is used here:
 * - The logic is scoped to block editor screens only by checking
 *   `get_current_screen()?->is_block_editor()`.
 *
 * @return void
 */
add_filter('admin_head', function () {
    if (! get_current_screen()?->is_block_editor()) {
        return;
    }

    $dependencies = json_decode(Vite::content('editor.deps.json'));

    foreach ($dependencies as $dependency) {
        if (! wp_script_is($dependency)) {
            wp_enqueue_script($dependency);
        }
    }

    echo Vite::withEntryPoints([
        'resources/js/editor.js',
    ])->toHtml();
});

/* =============================================================================
 * GENERATED theme.json HANDOFF
 * =============================================================================
 *
 * This project uses the build-generated `theme.json` rather than a manually
 * maintained root-level file.
 *
 * Why this matters:
 * - It keeps the editor design tokens aligned with the build output.
 * - It makes the generated file the effective source used by WordPress.
 * =============================================================================
 */

/**
 * Tell WordPress to use the generated `public/build/assets/theme.json`.
 *
 * Why this exists:
 * - The theme build process generates a `theme.json` file that reflects the
 *   design/token pipeline.
 * - This filter swaps WordPress's default theme file lookup so the generated
 *   file is used instead.
 *
 * @param string $path Resolved file path.
 * @param string $file Requested file name.
 * @return string
 */
add_filter('theme_file_path', function ($path, $file) {
    return $file === 'theme.json'
        ? public_path('build/assets/theme.json')
        : $path;
}, 10, 2);

/* =============================================================================
 * CORE THEME SETUP
 * =============================================================================
 *
 * This is the canonical WordPress theme setup section.
 *
 * Why `after_setup_theme` is important:
 * - WordPress expects core theme supports and menu registration to happen here.
 * - This hook runs early enough for features such as thumbnails and title-tag.
 * =============================================================================
 */

/**
 * Register the base theme setup.
 *
 * What belongs here:
 * - Theme supports
 * - Menu registration
 * - Broad theme feature toggles
 *
 * What does NOT belong here:
 * - Module loaders
 * - Admin-only CSS helpers
 * - Request-specific business logic
 *
 * @return void
 */
add_action('after_setup_theme', function () {
    /**
     * Disable block templates / full-site editing templates.
     *
     * Why:
     * - This theme is being used as a classic/Sage theme with Blade templates,
     *   not as an FSE-first theme.
     */
    remove_theme_support('block-templates');

    /**
     * Register navigation menu locations.
     *
     * These keys are the canonical handles used by the theme when requesting
     * menus in Blade/templates.
     */
    register_nav_menus([
        'primary_navigation'    => __('Primary Navigation', 'sage'),
        'legal_navigation'      => __('Legal Navigation', 'sage'),
    ]);

    /**
     * Disable WordPress core block patterns.
     *
     * Why:
     * - This keeps the editor more curated and avoids exposing default pattern
     *   choices that may not match the project design system.
     */
    remove_theme_support('core-block-patterns');

    /**
     * Allow WordPress/plugins to manage the document title tag.
     */
    add_theme_support('title-tag');

    /**
     * Enable featured image / post thumbnail support.
     */
    add_theme_support('post-thumbnails');

    /**
     * Enable responsive embedded content support.
     */
    add_theme_support('responsive-embeds');

    /**
     * Enable HTML5 markup support for common theme-generated elements.
     *
     * Why:
     * - Keeps theme output aligned with modern core markup expectations.
     */
    add_theme_support('html5', [
        'caption',
        'comment-form',
        'comment-list',
        'gallery',
        'search-form',
        'script',
        'style',
    ]);

    /**
     * Enable selective refresh support in the customizer.
     */
    add_theme_support('customize-selective-refresh-widgets');
}, 20);

