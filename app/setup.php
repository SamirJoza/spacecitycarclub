/* =============================================================================
 * PROJECT NOTE: CONTENT TYPE TAXONOMY
 * =============================================================================
 *
 * This trailing note documents the design intent for the Content Type taxonomy.
 * It is not executable code, but it is useful project knowledge.
 *
 * Recommendation:
 * - Keeping this note is reasonable because it explains editorial architecture.
 * - If you ever create dedicated internal docs, this is the kind of note that
 *   could move there instead of living in the boot file.
 * =============================================================================
 */

/*
 * Register the Content Type taxonomy.
 *
 * Why registered in code, terms managed in admin:
 * - The taxonomy structure (slug, rewrite rules, meta box behaviour) is
 *   architectural and belongs in version control.
 * - The actual terms (Event Recaps, Garage Talk…) are editorial content
 *   and belong in the database, managed via Posts → Content Types in
 *   wp-admin. This keeps code deploys and content management separate.
 *
 * To add/edit/delete terms:
 *   wp-admin → Posts → Content Types
 *
 * Why non-hierarchical + radio meta box:
 * - Content types are a flat, curated set — not a parent/child tree.
 * - Radio enforces one type per post (a post is a Spotlight OR Garage
 *   Talk, not both).
 *
 * Why mandatory (see validation hooks below):
 * - A post without a content type would not appear in any pill-filtered
 *   view and cannot be categorised correctly in the frontend.
 * - Validation is enforced at the REST API layer (Gutenberg) and at the
 *   wp_insert_post_data layer (classic editor) so neither editor can
 *   publish without selecting a type.
 */
