/**
 * Improve the ACF tab layout in admin by forcing a single-row tab strip with
 * horizontal scrolling when needed.
 *
 * Why this exists:
 * - Some larger field groups become hard to use when ACF wraps tabs awkwardly.
 * - This keeps tab navigation predictable on smaller admin widths.
 */
add_action('admin_enqueue_scripts', function () {
    $css = <<<CSS
    /* Keep ACF tabs in one row and allow horizontal scroll */
    .acf-fields .acf-tab-group{display:flex;flex-wrap:nowrap;gap:6px;overflow:auto}
    .acf-fields .acf-tab-group li{flex:0 0 auto}
    .acf-fields .acf-tab-group li a{white-space:nowrap}
    .acf-fields.-top > .acf-tab-wrap .acf-tab-group{margin-bottom:8px}
    CSS;

    /**
     * Prefer attaching the CSS to ACF's stylesheet handle if it is already
     * enqueued. If not, fall back to printing the CSS in `admin_head`.
     *
     * Why this fallback exists:
     * - It keeps the helper reliable even if ACF's enqueue timing differs
     *   slightly between screens.
     */
    if (wp_style_is('acf-input', 'enqueued')) {
        wp_add_inline_style('acf-input', $css);
    } else {
        add_action('admin_head', function () use ($css) {
            echo "<style>{$css}</style>";
        });
    }
});

